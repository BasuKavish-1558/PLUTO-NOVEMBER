/**
 * Compile-time guard: every table the app syncs must have exactly the server's columns.
 * `src/types/database.ts` is generated from the live project (`npm run db:types`); if a migration
 * and the local row types drift apart, `npm run typecheck` fails here. Type-only: emits no code.
 */
import type { Database } from '@/types/database'
import type { SyncedRows } from './db'

type ServerTables = Database['public']['Tables']
type Same<A, B> = [A] extends [B] ? ([B] extends [A] ? true : false) : false
type Expect<T extends true> = T

/** Server columns the client deliberately never reads (generated by the database). */
type ServerOnly = { exercises: 'is_custom' }
type ServerColumns<T extends keyof SyncedRows> = Exclude<keyof ServerTables[T]['Row'], T extends keyof ServerOnly ? ServerOnly[T] : never>

type Drift<T extends keyof SyncedRows> = Same<ServerColumns<T>, keyof SyncedRows[T]>

export type SchemaInSync = Expect<
  Drift<'profiles'> &
    Drift<'body_vitals'> &
    Drift<'exercises'> &
    Drift<'splits'> &
    Drift<'split_days'> &
    Drift<'split_day_exercises'> &
    Drift<'workouts'> &
    Drift<'workout_exercises'> &
    Drift<'set_logs'> &
    Drift<'workout_photos'> &
    Drift<'nutrition_goals'> &
    Drift<'nutrition_entries'> &
    Drift<'personal_records'>
>
